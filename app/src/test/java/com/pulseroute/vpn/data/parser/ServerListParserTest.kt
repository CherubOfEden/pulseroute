package com.pulseroute.vpn.data.parser

import com.pulseroute.vpn.data.model.Protocol
import com.pulseroute.vpn.data.model.TransportType
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertTrue
import org.junit.Test

class ServerListParserTest {

    @Test
    fun parsesFlatVmessWebSocketTlsEntry() {
        val payload = """
            [
              {
                "name": "Amsterdam",
                "address": "ams.example.com",
                "port": 443,
                "protocol": "vmess",
                "uuid": "11111111-1111-4111-8111-111111111111",
                "alterId": 0,
                "network": "ws",
                "path": "/ray",
                "host": "cdn.example.com",
                "tls": "tls",
                "sni": "cdn.example.com"
              }
            ]
        """.trimIndent()

        val server = ServerListParser.parse(payload).single()

        assertEquals(Protocol.VMESS, server.protocol)
        assertEquals("ams.example.com", server.address)
        assertEquals(443, server.port)
        assertEquals("Amsterdam", server.name)
        assertNotNull(server.vmess)
        assertEquals(TransportType.WS, server.vmess?.transport?.type)
        assertEquals("/ray", server.vmess?.transport?.path)
        assertEquals("cdn.example.com", server.vmess?.transport?.host)
        assertEquals("cdn.example.com", server.vmess?.tls?.serverName)
        assertEquals(true, server.vmess?.tls?.enabled)
    }

    @Test
    fun parsesServersJsWrapperWithCommentsAndTrailingComma() {
        val payload = """
            // generated by the panel
            const SERVERS = [
              {
                "name": "Tokyo",
                "address": "tokyo.example.com",
                "port": 443,
                "type": "vless",
                "id": "22222222-2222-4222-8222-222222222222",
                "flow": "xtls-rprx-vision",
                "network": "grpc",
                "serviceName": "pulse",
                "tls": "tls",
                "sni": "tokyo.example.com",
              },
            ];
        """.trimIndent()

        val server = ServerListParser.parse(payload).single()

        assertEquals(Protocol.VLESS, server.protocol)
        assertEquals("tokyo.example.com", server.address)
        assertEquals(TransportType.GRPC, server.vmess?.transport?.type ?: server.vless?.transport?.type)
        assertEquals("pulse", server.vless?.transport?.serviceName)
        assertEquals("xtls-rprx-vision", server.vless?.flow)
    }

    @Test
    fun parsesWireGuardEntry() {
        val payload = """
            {
              "servers": [
                {
                  "name": "Warp",
                  "address": "wg.example.com",
                  "port": 2408,
                  "protocol": "wireguard",
                  "privateKey": "private-key",
                  "publicKey": "peer-public-key",
                  "localAddress": ["172.16.0.2/32"],
                  "reserved": [1, 2, 3]
                }
              ]
            }
        """.trimIndent()

        val server = ServerListParser.parse(payload).single()

        assertEquals(Protocol.WIREGUARD, server.protocol)
        assertEquals("wg.example.com", server.address)
        assertEquals("private-key", server.wireGuard?.privateKey)
        assertEquals("peer-public-key", server.wireGuard?.peerPublicKey)
        assertEquals(listOf(1, 2, 3), server.wireGuard?.reserved)
        assertEquals(listOf("172.16.0.2/32"), server.wireGuard?.localAddresses)
    }

    @Test
    fun infersVlessWhenUuidAndFlowArePresent() {
        val payload = """
            [{"name":"x","server":"x.example.com","port":443,"id":"uuid","flow":"xtls-rprx-vision"}]
        """.trimIndent()

        assertEquals(Protocol.VLESS, ServerListParser.parse(payload).single().protocol)
    }

    @Test(expected = ServerParseException::class)
    fun rejectsPayloadWithoutServers() {
        ServerListParser.parse("""{"servers":[]}""")
    }

    @Test
    fun producesStableIds() {
        val payload = """
            [{"name":"a","address":"a.example.com","port":443,"type":"vless","id":"abc"}]
        """.trimIndent()

        val first = ServerListParser.parse(payload).single().id
        val second = ServerListParser.parse(payload).single().id

        assertTrue(first.isNotBlank())
        assertEquals(first, second)
        assertEquals(16, first.length)
    }
}
